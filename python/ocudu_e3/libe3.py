"""libe3's E3AP grammar in Python, byte-identical to libe3 and to the OCUDU agent.

libe3 (and OCUDU's libe3 codec) are generated by asn1c, which treats the SIZE
constraint of a ``UTF8String (SIZE (lo..hi))`` as PER-visible: the length is a
constrained bit field, then the octets. A strict X.691 encoder such as plain
asn1tools does not (UTF8String is not a known-multiplier type) and writes an
octet-aligned length determinant instead, so the two disagree on every PDU that
carries text -- E3-SetupRequest and E3-SetupResponse in libe3 0.2.1.

:func:`load_libe3_codec` compiles the vendored grammar with each constrained
``UTF8String`` read as an ``OCTET STRING`` with the same SIZE, which is exactly the
asn1c encoding, so Python peers interoperate with libe3 on all eleven procedures
(checked against libe3's own encoder output in python/tests). Text fields cross
the API as ``str`` and are UTF-8 on the wire; malformed UTF-8 is rejected.
"""
from __future__ import annotations

import os
import pathlib
import re

import asn1tools

#: Fields of the libe3 grammar that are UTF8String on the wire (and bytes inside asn1tools here).
TEXT_FIELDS = frozenset({"e3apProtocolVersion", "dAppName", "dAppVersion", "vendor", "ranIdentifier"})

_CONSTRAINED_UTF8 = re.compile(r"UTF8String\s*\(\s*SIZE")


def libe3_grammar_path(schema_dir: str | os.PathLike | None = None) -> pathlib.Path:
    """The vendored libe3 grammar: ``<schema dir>/interop/libe3/e3ap-1.0.0.asn1``."""
    if schema_dir is None:
        schema_dir = os.environ.get("OCUDU_E3_SCHEMA_DIR") or pathlib.Path(__file__).resolve().parents[2] / "schemas" / "e3"
    return pathlib.Path(schema_dir) / "interop" / "libe3" / "e3ap-1.0.0.asn1"


def asn1c_equivalent_grammar(text: str) -> str:
    """The grammar with every SIZE-constrained UTF8String read the way asn1c encodes it."""
    rewritten = _CONSTRAINED_UTF8.sub("OCTET STRING (SIZE", text)
    if "UTF8String" in rewritten:
        # An unconstrained UTF8String encodes identically everywhere; a new constrained form
        # this rewrite does not recognise must not slip through silently.
        unconstrained = re.findall(r"UTF8String(?!\s*\()", rewritten)
        if len(unconstrained) != rewritten.count("UTF8String"):
            raise ValueError("libe3 grammar has a UTF8String form the asn1c-equivalent rewrite does not handle")
    return rewritten


def load_libe3_codec(schema_dir: str | os.PathLike | None = None):
    """asn1tools PER codec for libe3's E3AP module that encodes exactly like asn1c/libe3."""
    return asn1tools.compile_string(asn1c_equivalent_grammar(libe3_grammar_path(schema_dir).read_text()), "per")


def _to_wire(value):
    if isinstance(value, dict):
        return {key: (item.encode("utf-8") if key in TEXT_FIELDS and isinstance(item, str) else _to_wire(item))
                for key, item in value.items()}
    if isinstance(value, list):
        return [_to_wire(item) for item in value]
    if isinstance(value, tuple):
        return tuple(_to_wire(item) for item in value)
    return value


def _from_wire(value):
    if isinstance(value, dict):
        return {key: (item.decode("utf-8") if key in TEXT_FIELDS and isinstance(item, bytes) else _from_wire(item))
                for key, item in value.items()}
    if isinstance(value, list):
        return [_from_wire(item) for item in value]
    if isinstance(value, tuple):
        return tuple(_from_wire(item) for item in value)
    return value


class Libe3Codec:
    """E3-PDU encode/decode in libe3's dialect with text fields as ``str``."""

    def __init__(self, schema_dir: str | os.PathLike | None = None):
        self._codec = load_libe3_codec(schema_dir)

    def encode(self, pdu: dict) -> bytes:
        return self._codec.encode("E3-PDU", _to_wire(pdu))

    def decode(self, data: bytes) -> dict:
        return _from_wire(self._codec.decode("E3-PDU", data))
